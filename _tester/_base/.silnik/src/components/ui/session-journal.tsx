  character: Character;
  model?: PublicJournal;
  onReadCard?: (card: JournalCard) => void;
  onUpdateCharacter?: (character: Character) => void;
  onClose?: () => void;
  currentInGameDate?: string;
  sharedJournal?: JournalEntry[];
  onUpdateSharedJournal?: (journal: JournalEntry[]) => void;
