import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {buildSceneReview,validateSceneDecisionDocument} from './scene-review.mjs';
import {renderSceneReview} from './scene-review-render.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const require=createRequire(path.join(root,'_tester/_base/.silnik/package.json'));
const {chromium}=require('@playwright/test');
test('offline decisions: validation, exceptions, export and import execute in browser',async()=>{
 const directory=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'review-browser-')));
 const manifest={adventure_id:'fixture',edition_fingerprint:'sha256:fixture',language:'pl'};
 const card=(id,scenes)=>({record_id:id,adventure_id:manifest.adventure_id,edition_fingerprint:manifest.edition_fingerprint,content:'Neutral source '+id,tags:{scenes,entities:[]},links:[],evidence:{approval:'pending'}});
 const model=buildSceneReview({manifest,records:[card('one',['opening']),{...card('witness',['opening']),record_type:'actor',content:JSON.stringify({value:{name:'Witness',description:'Waits nearby'}})},card('unmapped',['unknown'])],review:{supplement:{scene_frames:[{id:'opening',title:'Neutral opening',focus:'A neutral scene',state:'No automatic effects'}]}}});
 const html=path.join(directory,'index.html');fs.writeFileSync(html,renderSceneReview({model,title:'Neutral fixture',media:[{id:'global-image',label:'Global image',kind:'image',preview_url:'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=',language:'pl',source_refs:['fixture.json#/image']},{id:'global-audio',label:'Global audio',kind:'audio',preview_url:'file:///private/test-audio.mp3',language:'en',source_refs:['fixture.json#/audio']}]}));
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(html).href);
  assert.match(await page.locator('[data-testid="author-review-guide"]').innerText(),/fragmenty jednego opisu/);
  assert.match(await page.locator('#groups button').first().innerText(),/2 fragmentów źródła/);
  assert.match(await page.locator('#scene').innerText(),/Osoby opisane w źródle tej sceny/);
  assert.match(await page.locator('#scene').innerText(),/To nie jest lista postaci do wyboru/);
  assert.equal(await page.locator('#scene img, #scene audio').count(),0);
  await page.getByRole('button',{name:'Obrazy i nagrania przygody',exact:true}).click();
  assert.equal(await page.locator('#media-library').evaluate(e=>e.open),true);
  assert.equal(await page.locator('#media-library article').count(),2);
  assert.equal(await page.locator('#media-library img').count(),1);
  assert.equal(await page.locator('#media-library audio').count(),1);
  assert.equal(await page.locator('#media-library audio').evaluate(e=>e.autoplay),false);
  assert.equal(await page.locator('[data-check]').count(),6);
  for(const label of await page.locator('.check label').allTextContents())assert.match(label.trim(),/^Tak,/);
  await page.locator('#reviewer').fill('Fixture reviewer');
  await page.getByRole('button',{name:'Zatwierdzam opisany zestaw i pobieram decyzję',exact:true}).click();
  await page.getByRole('status').filter({hasText:'sześć punktów'}).waitFor();
  for(const checkbox of await page.locator('[data-check]').all())await checkbox.check();
  const downloaded=page.waitForEvent('download');await page.locator('[data-decision=accepted]').click();const file=await downloaded;
  const accepted=validateSceneDecisionDocument(model,fs.readFileSync(await file.path(),'utf8'));assert.equal(accepted.decisions[0].status,'accepted');assert.equal(accepted.decisions[0].snapshot,model.groups[0].snapshot);
  await page.locator('[data-group=exceptions]').click();
  for(const checkbox of await page.locator('[data-check]').all())await checkbox.check();
  await page.locator('[data-decision=accepted]').click();assert.match(await page.locator('#message').innerText(),/wyjątków/);
  const deferredDownload=page.waitForEvent('download');await page.locator('[data-decision=deferred]').click();await deferredDownload;
  const duplicate={...accepted,decisions:[...accepted.decisions,...accepted.decisions]};
  await page.locator('#import-file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(duplicate))});
  await page.waitForFunction(()=>document.getElementById('message').textContent.includes('Nie wczytano decyzji'));
  assert.match(await page.locator('#message').innerText(),/Duplicate/);
  await page.locator('#import-file').setInputFiles({name:'valid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(accepted))});
  await page.waitForFunction(()=>document.getElementById('message').textContent.includes('Wczytano decyzje.'));
  await page.locator('[data-group="scene:opening"]').click();assert.match(await page.locator('#decision-status').innerText(),/Zatwierdzone/);
  assert.deepEqual(errors,[]);
 }finally{await browser.close();}
});
